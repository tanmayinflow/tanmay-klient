let activePlayer = null;
export function claimMotionPlayer(player) {
  if (activePlayer && activePlayer !== player) activePlayer.pause();
  activePlayer = player;
}
export function releaseMotionPlayer(player) {
  player.pause();
  if (activePlayer === player) activePlayer = null;
}
