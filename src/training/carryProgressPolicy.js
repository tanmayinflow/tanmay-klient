function same(a, b) {
  if (Object.is(a, b)) return true;
  if (!a || !b || typeof a !== "object" || typeof b !== "object" || Array.isArray(a) !== Array.isArray(b)) return false;
  const keys = Object.keys(a);
  return keys.length === Object.keys(b).length && keys.every(key => Object.hasOwn(b, key) && same(a[key], b[key]));
}

function matches(row, signature) {
  return Object.entries(signature).every(([key, expected]) =>
    Object.hasOwn(row, key) === expected.present && (!expected.present || same(row[key], expected.value)));
}

export function carryAllowsEstimatedMax(rawrow) {
  if (!rawrow || typeof rawrow !== "object" || Array.isArray(rawrow) || !Object.hasOwn(rawrow, "id")) return undefined;
  const profile = Object.hasOwn(profiles, rawrow.id) ? profiles[rawrow.id] : null;
  if (!profile || ![profile.before, profile.after, profile.freshBefore, profile.freshAfter].some(signature => matches(rawrow, signature))) return undefined;
  // Navigation labels, priority, scores and personal notes do not redefine the
  // task. A conflicting explicit movement, position, support or tool does.
  if (Object.hasOwn(rawrow, "taxonomy")) {
    const tax = rawrow.taxonomy;
    if (!tax || typeof tax !== "object" || Array.isArray(tax)) return undefined;
    for (const [key, expected] of Object.entries(profile.semanticTaxonomy)) {
      if (Object.hasOwn(tax, key) && !same(tax[key], expected)) return undefined;
    }
  }
  return false;
}
