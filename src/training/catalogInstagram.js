/** Add new cards once. Preserve personal edits, subsequent deletions, plans and logs. */
export function seedInstagramExpansion(collection, seedRows = INSTAGRAM_EXERCISES) {
  if (!collection || collection.instagramExpansion20261015) return collection;
  const previous = collection.tEx || [];
  const have = new Set(previous.map(row => row.id));
  const additions = [];
  for (const row of seedRows) {
    if (!row.id.startsWith('ig26_') || have.has(row.id)) continue;
    have.add(row.id);
    additions.push(row);
  }
  // A user may have deleted a baseline progression target. Do not restore it
  // or introduce a dead link on a newly added card. Existing cards are untouched.
  const linked = additions.map(row => {
    const ez = row.ez && have.has(row.ez) ? row.ez : null;
    const hd = row.hd && have.has(row.hd) ? row.hd : null;
    return ez === row.ez && hd === row.hd ? row : { ...row, ez, hd };
  });
  return { ...collection, instagramExpansion20261015: true, tEx: linked.length ? [...previous, ...linked] : previous };
}
